"""训练视频分析交给管家（spec [2026-10-23] §224）。

分析在用户自己的设备上做（摄像头看动作的同一套规则），结果写成一段〔动作视频分析〕文字跟在他的话后面发来；
视频本身不发。这里只认出这段，告诉管家这些数是怎么来的、怎么点评。
"""

from __future__ import annotations

OPEN, CLOSE = "〔动作视频分析〕", "〔/动作视频分析〕"

NOTE = (
    "他这句带了一段〔动作视频分析〕：是他手机上按固定规则从视频里的关节点算出来的（次数、每一下的问题、"
    "每种问题量的是什么和依据），不是你看了视频，也不是他自己的感觉。点评时：先一句话说这组整体怎么样；"
    "再挑最要紧的一个问题，说可能的原因和下一组怎么改（一两条做法）；没有问题就说保持。只按算出来的说，"
    "不编造视频里没算出来的问题，不说你看了视频；阈值是经验值、拍的角度会影响判断，他觉得不对可以换个角度再拍。"
)


def has_report(text: str) -> bool:
    i = text.find(OPEN)
    return i >= 0 and text.find(CLOSE, i) > i


def video_note(text: str) -> str:
    return NOTE if has_report(text) else ""
